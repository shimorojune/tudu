import { readFile } from "node:fs/promises";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(root, "../..");

async function loadRepoEnv() {
  try {
    const raw = await readFile(path.join(repoRoot, ".env"), "utf8");
    for (const line of raw.split("\n")) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) {
        continue;
      }
      const eq = trimmed.indexOf("=");
      if (eq === -1) {
        continue;
      }
      const key = trimmed.slice(0, eq).trim();
      const value = trimmed.slice(eq + 1).trim();
      if (key.startsWith("VITE_FIREBASE_") && !process.env[key]) {
        process.env[key] = value;
      }
    }
  } catch {
    // No local .env; rely on process.env (Docker build args).
  }
}

await loadRepoEnv();
const publicDir = path.join(root, "public");
const outPath = path.join(publicDir, "fcm-sw-import.js");

const config = {
  apiKey: process.env.VITE_FIREBASE_API_KEY ?? "",
  authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN ?? "",
  projectId: process.env.VITE_FIREBASE_PROJECT_ID ?? "",
  messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID ?? "",
  appId: process.env.VITE_FIREBASE_APP_ID ?? "",
};

const hasConfig = Object.values(config).every((value) => value.length > 0);

const contents = hasConfig
  ? `/* Generated by apps/web/scripts/generate-firebase-messaging-sw.mjs (Workbox importScripts) */
importScripts("https://www.gstatic.com/firebasejs/11.10.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/11.10.0/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(config)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const data = payload.data ?? {};
  const title = data.title || "Tudu";
  const body = data.body || "";
  const options = {
    body,
    data,
    tag: data.tag || data.kind || "tudu",
    icon: "/pwa-192.png",
    badge: "/pwa-192.png",
  };
  self.registration.showNotification(title, options);
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const data = event.notification.data ?? {};
  let url = "/";
  if (data.kind === "regular" || data.path === "/today") {
    url = "/";
  } else if (data.kind === "inbox" || data.kind === "inbox_declined") {
    url = "/inbox";
  } else if (data.taskId) {
    const params = new URLSearchParams();
    params.set("task", data.taskId);
    if (data.scheduledDate) {
      params.set("date", data.scheduledDate);
    }
    if (data.kind === "comment") {
      params.set("tab", "comments");
    }
    url = \`/?\${params.toString()}\`;
  }
  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((windowClients) => {
      for (const client of windowClients) {
        if (client.url.includes(self.location.origin)) {
          client.focus();
          client.navigate(url);
          return;
        }
      }
      if (clients.openWindow) {
        return clients.openWindow(url);
      }
    }),
  );
});
`
  : `/* Firebase web push is not configured (missing VITE_FIREBASE_* env). */\n`;

await mkdir(publicDir, { recursive: true });
await writeFile(outPath, contents, "utf8");
console.log(
  hasConfig
    ? `Wrote ${outPath}`
    : `Wrote stub ${outPath} (no Firebase env; web push disabled)`,
);
