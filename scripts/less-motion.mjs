#!/usr/bin/env node
// Settings › Appearance › Less motion: every rule the stylesheets keep for the computer's Reduce motion setting,
// again under :root[data-motion='less'], so the switch in Tudu gives the same simple fades.
// `node scripts/less-motion.mjs` writes packages/ui/src/styles/less-motion.css; `--check` fails when it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'packages', 'ui', 'src', 'styles');
const SOURCES = ['paper-theme.css', 'components.css', 'app.css'];
const OUT = join(root, 'less-motion.css');
const PREFIX = ":root[data-motion='less']";

/** The inside of every `@media (prefers-reduced-motion: reduce) { … }` block in a stylesheet. */
export function reducedBlocks(css) {
  const out = [];
  const re = /@media\s*\(prefers-reduced-motion:\s*reduce\)\s*\{/g;
  while (re.exec(css)) {
    let depth = 1;
    let i = re.lastIndex;
    const start = i;
    for (; i < css.length && depth; i++) {
      if (css[i] === '{') depth++;
      else if (css[i] === '}') depth--;
    }
    out.push(css.slice(start, i - 1));
    re.lastIndex = i;
  }
  return out;
}

/** One block's rules with each selector put under the Less motion switch. */
export function underSwitch(block) {
  const rules = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  const clean = block.replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of clean.matchAll(re)) {
    const selectors = m[1]
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
      .map((s) => `${PREFIX} ${s}`);
    const decls = m[2]
      .split(';')
      .map((d) => d.trim())
      .filter(Boolean)
      .map((d) => `  ${d};`);
    rules.push(`${selectors.join(',\n')} {\n${decls.join('\n')}\n}`);
  }
  return rules;
}

export function lessMotionCss(read = (f) => readFileSync(join(root, f), 'utf8')) {
  const parts = [
    '/* Generated by scripts/less-motion.mjs from the reduced-motion rules of paper-theme.css, components.css and',
    "   app.css. Settings › Appearance › Less motion sets data-motion='less' on the page. Do not edit by hand. */",
  ];
  for (const f of SOURCES) {
    const rules = reducedBlocks(read(f)).flatMap(underSwitch);
    if (rules.length) parts.push(`\n/* ${f} */`, ...rules);
  }
  return parts.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = lessMotionCss();
  if (process.argv.includes('--check')) {
    const now = readFileSync(OUT, 'utf8');
    if (now !== next) {
      console.error('less-motion.css is stale: run node scripts/less-motion.mjs');
      process.exit(1);
    }
  } else writeFileSync(OUT, next);
}
