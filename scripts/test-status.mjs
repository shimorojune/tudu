#!/usr/bin/env node
// Rewrite docs/tests/STATUS.md from the last test run: reports/vitest.json, reports/playwright.json and, for the
// desktop group (the real macOS app), reports/playwright-mac.json. Every case id (C00-U01, C01-E03, C11-D02 ...) found
// in test names is listed with pass, fail or skipped, grouped by chunk.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const ID = /\bC(\d\d)-([UAED])(\d\d)\b/g;
const status = new Map(); // id -> state
// A case runs on several viewports; one failure makes it FAIL, otherwise one pass makes it pass (a viewport that
// skips it by design does not take that away), and skipped means it ran nowhere.
const RANK = { fail: 3, pass: 2, skip: 1 };

function note(id, state) {
  const prev = status.get(id);
  if (!prev || RANK[state] > RANK[prev]) status.set(id, state);
}

const vitestPath = join(ROOT, 'reports/vitest.json');
if (existsSync(vitestPath)) {
  const report = JSON.parse(readFileSync(vitestPath, 'utf8'));
  for (const file of report.testResults ?? []) {
    for (const t of file.assertionResults ?? []) {
      const name = [...(t.ancestorTitles ?? []), t.title].join(' ');
      for (const m of name.matchAll(ID))
        note(m[0], t.status === 'passed' ? 'pass' : t.status === 'failed' ? 'fail' : 'skip');
    }
  }
}
for (const pwPath of [join(ROOT, 'reports/playwright.json'), join(ROOT, 'reports/playwright-mac.json')]) {
  if (!existsSync(pwPath)) continue;
  const report = JSON.parse(readFileSync(pwPath, 'utf8'));
  const walk = (suite) => {
    for (const spec of suite.specs ?? []) {
      const name = `${suite.title} ${spec.title}`;
      const ok = spec.tests.every((t) => t.status === 'expected' || t.status === 'skipped');
      const skipped = spec.tests.every((t) => t.status === 'skipped');
      for (const m of name.matchAll(ID)) note(m[0], skipped ? 'skip' : ok ? 'pass' : 'fail');
    }
    for (const s of suite.suites ?? []) walk(s);
  };
  for (const s of report.suites ?? []) walk(s);
}

const chunks = new Map();
for (const [id, state] of status) {
  const chunk = id.slice(0, 3);
  if (!chunks.has(chunk)) chunks.set(chunk, []);
  chunks.get(chunk).push([id, state]);
}
const mark = { pass: 'pass', fail: 'FAIL', skip: 'skipped' };
const lines = [
  '# Test status',
  '',
  `Generated by \`pnpm test:status\` on ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC from the last local or CI run.`,
  '',
];
if (!chunks.size) lines.push('No reports found. Run `pnpm test` and `pnpm e2e` first.');
for (const [chunk, rows] of [...chunks].sort()) {
  rows.sort((a, b) => a[0].localeCompare(b[0]));
  const passed = rows.filter((r) => r[1] === 'pass').length;
  lines.push(
    `## Chunk ${chunk.slice(1)}: ${passed} of ${rows.length} passing`,
    '',
    '| Case | Status |',
    '|---|---|',
  );
  for (const [id, state] of rows) lines.push(`| ${id} | ${mark[state]} |`);
  lines.push('');
}
writeFileSync(join(ROOT, 'docs/tests/STATUS.md'), lines.join('\n'));
console.log(`docs/tests/STATUS.md: ${status.size} cases`);
